"""
test_gold_standard.py

Real evaluation harness for the Legality AI risk-detection model.
Runs against backend/dataset/synthetic_gold_standard_with_nli.json using
the same embedding model RiskDetector uses in production
(backend/vector_search.py: "bhavibhatt/legal_model", falling back to
"all-MiniLM-L6-v2" if that's unavailable).

This runs the 5 tests the README advertises:
  1. Risky Clause Detection   - are risky_clause entries flagged?
  2. Safe Clause Rejection    - are safe_clause entries NOT flagged?
  3. Threshold Sensitivity    - precision/recall/F1 across a threshold sweep
  4. NLI Hypothesis Similarity- do risky clauses score higher against their
                                 OWN category hypothesis than other categories?
  5. Category-Specific Accuracy - per-category precision/recall/F1/accuracy

It also reports ranking metrics (NDCG@5, MRR) by treating each category's
NLI hypothesis as a retrieval query over the full pool of clauses.

Usage:
    cd ml/evaluation
    pip install -r requirements.txt
    python test_gold_standard.py
    python test_gold_standard.py --threshold 0.55
    python test_gold_standard.py --thresholds 0.3,0.4,0.5,0.6,0.7,0.8,0.9

Notes / honesty about what this measures:
    - The gold standard is small (currently ~46 base entries -> ~92 labeled
      examples once risky/safe pairs are split out) and the "safe_clause"
      side was generated by an LLM rewrite, not a human legal reviewer.
      Treat absolute numbers as directional, not production-grade
      statistical claims, until the dataset grows and is human-validated.
      See docs/EVALUATION.md for the full discussion.
"""

import argparse
import json
import sys
from pathlib import Path

import numpy as np

THIS_DIR = Path(__file__).resolve().parent
REPO_ROOT = THIS_DIR.parent.parent
DATASET_PATH = REPO_ROOT / "backend" / "dataset" / "synthetic_gold_standard_with_nli.json"
RESULTS_DIR = THIS_DIR / "results"

sys.path.insert(0, str(THIS_DIR))
from metrics import (  # noqa: E402
    confusion_counts,
    precision_recall_f1,
    accuracy_score,
    false_positive_rate,
    false_negative_rate,
    ndcg_at_k,
    mean_reciprocal_rank,
)

DEFAULT_THRESHOLDS = [0.30, 0.35, 0.40, 0.45, 0.50, 0.55, 0.60, 0.65, 0.70, 0.75, 0.80, 0.85, 0.90]


# ---------------------------------------------------------------------------
# Data loading
# ---------------------------------------------------------------------------
def load_gold_standard(path: Path = DATASET_PATH) -> list:
    if not path.exists():
        raise FileNotFoundError(
            f"Gold standard dataset not found at {path}.\n"
            f"Expected backend/dataset/synthetic_gold_standard_with_nli.json"
        )
    with open(path) as f:
        data = json.load(f)
    if not data:
        raise ValueError(f"Gold standard dataset at {path} is empty.")
    return data


def build_labeled_examples(gold_standard: list) -> list:
    """
    Each gold-standard entry contributes two labeled examples:
      - risky_clause -> label=1 (should be flagged for its category)
      - safe_clause  -> label=0 (should NOT be flagged for its category)
    """
    examples = []
    skipped = 0
    for item in gold_standard:
        if not item.get("risky_clause") or not item.get("category"):
            skipped += 1
            continue
        examples.append({
            "id": f"{item['id']}_risky",
            "text": item["risky_clause"],
            "category": item["category"],
            "label": 1,
        })
        if item.get("safe_clause"):
            examples.append({
                "id": f"{item['id']}_safe",
                "text": item["safe_clause"],
                "category": item["category"],
                "label": 0,
            })
        else:
            skipped += 1
    if skipped:
        print(f"[INFO] Skipped {skipped} gold-standard entries with missing fields.")
    return examples


def get_category_hypotheses(gold_standard: list) -> dict:
    """category -> nli_hypothesis, taking the first one seen per category
    (mirrors RiskDetector.load_gold_standard in backend/vector_search.py)."""
    hypotheses = {}
    for item in gold_standard:
        cat = item.get("category")
        if cat and cat not in hypotheses:
            hypotheses[cat] = item.get("nli_hypothesis", cat)
    return hypotheses


# ---------------------------------------------------------------------------
# Model loading / embedding (mirrors backend/vector_search.py's RiskDetector)
# ---------------------------------------------------------------------------
def get_model():
    from sentence_transformers import SentenceTransformer
    hf_model_id = "bhavibhatt/legal_model"
    try:
        print(f"Loading model from Hugging Face: {hf_model_id}...")
        return SentenceTransformer(hf_model_id)
    except Exception as e:
        print(f"[WARN] Could not load '{hf_model_id}' ({e}); "
              f"falling back to 'all-MiniLM-L6-v2'.")
        return SentenceTransformer("all-MiniLM-L6-v2")


def compute_similarity_matrix(model, examples: list, categories: list, hypotheses: dict) -> np.ndarray:
    """sims[i][j] = cosine similarity between examples[i]'s text and
    categories[j]'s NLI hypothesis."""
    from sklearn.metrics.pairwise import cosine_similarity
    texts = [e["text"] for e in examples]
    hyp_texts = [hypotheses[c] for c in categories]
    text_emb = model.encode(texts, show_progress_bar=False)
    hyp_emb = model.encode(hyp_texts, show_progress_bar=False)
    return cosine_similarity(text_emb, hyp_emb)


# ---------------------------------------------------------------------------
# Test 1 + 2: Risky Clause Detection / Safe Clause Rejection (binary @ threshold)
# ---------------------------------------------------------------------------
def evaluate_at_threshold(examples: list, sims: np.ndarray, categories: list, threshold: float) -> dict:
    """
    An example is "flagged" if its similarity to its OWN category's
    hypothesis is >= threshold.
      - label=1 (risky_clause) flagged   -> TP  (Test 1: correctly detected)
      - label=1 (risky_clause) missed    -> FN
      - label=0 (safe_clause)  flagged   -> FP  (Test 2: false alarm)
      - label=0 (safe_clause)  not flag  -> TN  (Test 2: correctly rejected)
    """
    y_true, y_pred = [], []
    for i, ex in enumerate(examples):
        cat_idx = categories.index(ex["category"])
        score = sims[i][cat_idx]
        y_true.append(ex["label"])
        y_pred.append(int(score >= threshold))

    tp, fp, tn, fn = confusion_counts(y_true, y_pred)
    pr = precision_recall_f1(tp, fp, fn)
    return {
        "threshold": threshold,
        "tp": tp, "fp": fp, "tn": tn, "fn": fn,
        "precision": pr["precision"],
        "recall": pr["recall"],
        "f1": pr["f1"],
        "accuracy": accuracy_score(tp, tn, fp, fn),
        "false_positive_rate": false_positive_rate(fp, tn),
        "false_negative_rate": false_negative_rate(fn, tp),
    }


# ---------------------------------------------------------------------------
# Test 3: Threshold sensitivity sweep
# ---------------------------------------------------------------------------
def test_threshold_sensitivity(examples, sims, categories, thresholds):
    sweep = [evaluate_at_threshold(examples, sims, categories, t) for t in thresholds]
    best = max(sweep, key=lambda r: r["f1"])
    return sweep, best


# ---------------------------------------------------------------------------
# Test 4: NLI hypothesis similarity (own-category vs. other-category contrast)
# ---------------------------------------------------------------------------
def test_nli_hypothesis_similarity(examples, sims, categories):
    own, other = [], []
    for i, ex in enumerate(examples):
        if ex["label"] != 1:
            continue  # only risky clauses are expected to match their hypothesis
        cat_idx = categories.index(ex["category"])
        own.append(sims[i][cat_idx])
        other.extend(sims[i][j] for j in range(len(categories)) if j != cat_idx)
    return {
        "mean_similarity_to_own_hypothesis": float(np.mean(own)) if own else 0.0,
        "mean_similarity_to_other_hypotheses": float(np.mean(other)) if other else 0.0,
        "separation": float(np.mean(own) - np.mean(other)) if own and other else 0.0,
    }


# ---------------------------------------------------------------------------
# Test 5: Category-specific accuracy
# ---------------------------------------------------------------------------
def test_category_accuracy(examples, sims, categories, threshold):
    per_category = {}
    for cat in categories:
        cat_idx = categories.index(cat)
        idxs = [i for i, e in enumerate(examples) if e["category"] == cat]
        y_true = [examples[i]["label"] for i in idxs]
        y_pred = [int(sims[i][cat_idx] >= threshold) for i in idxs]
        tp, fp, tn, fn = confusion_counts(y_true, y_pred)
        pr = precision_recall_f1(tp, fp, fn)
        per_category[cat] = {
            "n": len(idxs),
            "accuracy": accuracy_score(tp, tn, fp, fn),
            "precision": pr["precision"],
            "recall": pr["recall"],
            "f1": pr["f1"],
        }
    return per_category


# ---------------------------------------------------------------------------
# Ranking metrics: NDCG@5 / MRR -- one retrieval query per category hypothesis
# ---------------------------------------------------------------------------
def test_ranking_metrics(examples, sims, categories, k=5):
    ndcgs, relevance_lists = {}, []
    for cat_idx, cat in enumerate(categories):
        order = np.argsort(-sims[:, cat_idx])
        relevances = [
            1 if (examples[i]["category"] == cat and examples[i]["label"] == 1) else 0
            for i in order
        ]
        ndcgs[cat] = ndcg_at_k(relevances, k)
        relevance_lists.append(relevances)
    return {
        "ndcg_at_5_per_category": ndcgs,
        "ndcg_at_5_macro": float(np.mean(list(ndcgs.values()))),
        "mrr": mean_reciprocal_rank(relevance_lists),
    }


# ---------------------------------------------------------------------------
# Reporting
# ---------------------------------------------------------------------------
def print_report(overall, sweep, best, nli, per_category, ranking, threshold_used):
    print("\n" + "=" * 70)
    print("GOLD STANDARD EVALUATION REPORT")
    print("=" * 70)

    print(f"\n--- Tests 1+2: Detection & Rejection @ threshold={threshold_used} ---")
    print(f"  TP={overall['tp']}  FP={overall['fp']}  TN={overall['tn']}  FN={overall['fn']}")
    print(f"  Precision: {overall['precision']:.3f}")
    print(f"  Recall:    {overall['recall']:.3f}")
    print(f"  F1:        {overall['f1']:.3f}")
    print(f"  Accuracy:  {overall['accuracy']:.3f}")
    print(f"  FPR:       {overall['false_positive_rate']:.3f}")
    print(f"  FNR:       {overall['false_negative_rate']:.3f}")

    print(f"\n--- Test 3: Threshold Sensitivity ---")
    print(f"  {'thresh':>7} {'prec':>7} {'recall':>7} {'f1':>7} {'acc':>7}")
    for r in sweep:
        marker = "  <-- best F1" if r is best else ""
        print(f"  {r['threshold']:>7.2f} {r['precision']:>7.3f} {r['recall']:>7.3f} "
              f"{r['f1']:>7.3f} {r['accuracy']:>7.3f}{marker}")

    print(f"\n--- Test 4: NLI Hypothesis Similarity ---")
    print(f"  Mean similarity to OWN category hypothesis:   {nli['mean_similarity_to_own_hypothesis']:.3f}")
    print(f"  Mean similarity to OTHER category hypotheses: {nli['mean_similarity_to_other_hypotheses']:.3f}")
    print(f"  Separation (own - other):                     {nli['separation']:.3f}")

    print(f"\n--- Test 5: Category-Specific Accuracy @ threshold={threshold_used} ---")
    print(f"  {'category':<32} {'n':>4} {'acc':>7} {'prec':>7} {'recall':>7} {'f1':>7}")
    for cat, m in per_category.items():
        print(f"  {cat:<32} {m['n']:>4} {m['accuracy']:>7.3f} {m['precision']:>7.3f} "
              f"{m['recall']:>7.3f} {m['f1']:>7.3f}")

    print(f"\n--- Ranking Metrics (NDCG@5 / MRR, hypothesis-as-query retrieval) ---")
    for cat, score in ranking["ndcg_at_5_per_category"].items():
        print(f"  NDCG@5 [{cat}]: {score:.3f}")
    print(f"  NDCG@5 (macro avg): {ranking['ndcg_at_5_macro']:.3f}")
    print(f"  MRR:                {ranking['mrr']:.3f}")
    print("\n" + "=" * 70)


def save_results(payload: dict, results_dir: Path = RESULTS_DIR):
    results_dir.mkdir(parents=True, exist_ok=True)
    out_path = results_dir / "latest_results.json"
    with open(out_path, "w") as f:
        json.dump(payload, f, indent=2)
    print(f"\nSaved machine-readable results to {out_path}")


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------
def main():
    parser = argparse.ArgumentParser(description="Evaluate the risk-detection model against the gold standard.")
    parser.add_argument("--threshold", type=float, default=0.50,
                         help="Threshold to use for Tests 1, 2, and 5 (default: 0.50, matching "
                              "RiskDetector's default in backend/vector_search.py).")
    parser.add_argument("--thresholds", type=str, default=None,
                         help="Comma-separated list of thresholds for the Test 3 sweep "
                              "(default: 0.30..0.90 in steps of 0.05).")
    args = parser.parse_args()

    thresholds = (
        [float(t) for t in args.thresholds.split(",")] if args.thresholds else DEFAULT_THRESHOLDS
    )

    print(f"Loading gold standard from {DATASET_PATH} ...")
    gold_standard = load_gold_standard()
    examples = build_labeled_examples(gold_standard)
    hypotheses = get_category_hypotheses(gold_standard)
    categories = list(hypotheses.keys())

    print(f"Loaded {len(gold_standard)} gold-standard entries -> "
          f"{len(examples)} labeled examples across {len(categories)} categories.")

    model = get_model()
    print("Computing embeddings and similarity matrix...")
    sims = compute_similarity_matrix(model, examples, categories, hypotheses)

    overall = evaluate_at_threshold(examples, sims, categories, args.threshold)
    sweep, best = test_threshold_sensitivity(examples, sims, categories, thresholds)
    nli = test_nli_hypothesis_similarity(examples, sims, categories)
    per_category = test_category_accuracy(examples, sims, categories, args.threshold)
    ranking = test_ranking_metrics(examples, sims, categories, k=5)

    print_report(overall, sweep, best, nli, per_category, ranking, args.threshold)

    print(f"\nNOTE: best F1 ({best['f1']:.3f}) occurs at threshold={best['threshold']}, "
          f"vs. the {args.threshold} used for the main report above.")

    save_results({
        "dataset_path": str(DATASET_PATH),
        "n_gold_standard_entries": len(gold_standard),
        "n_labeled_examples": len(examples),
        "categories": categories,
        "threshold_used": args.threshold,
        "overall": overall,
        "threshold_sweep": sweep,
        "best_threshold": best,
        "nli_hypothesis_similarity": nli,
        "per_category": per_category,
        "ranking_metrics": ranking,
    })


if __name__ == "__main__":
    main()
